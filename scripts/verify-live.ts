import assert from 'node:assert/strict';
const base = new URL(process.argv[2] || '');
assert.equal(base.protocol, 'https:', 'Use the public HTTPS share URL.');
const fetchPublic = async (url: URL | string, bot = false) => {
  const response = await fetch(url, { headers: bot ? { 'User-Agent': 'Twitterbot/1.0' } : {}, signal: AbortSignal.timeout(20000) });
  assert.equal(response.status, 200, `${url}: expected public HTTP 200, got ${response.status}`);
  return response;
};
const response = await fetchPublic(base, true), html = await response.text();
const head = html.split('</head>')[0];
const tags = [...head.matchAll(/<meta\s+(?:name|property)="([^"]+)"\s+content="([^"]*)"/g)];
const values = (key: string) => tags.filter(tag => tag[1] === key).map(tag => tag[2].replaceAll('&amp;', '&'));
assert.deepEqual(values('twitter:card'), ['player']);
assert.equal(values('twitter:player:stream').length, 0);
assert.equal(values('twitter:player').length, 1);
assert.equal(values('og:url')[0], base.href, 'Canonical URL must match this public deployment.');
for (const key of ['twitter:player:width', 'twitter:player:height']) assert.ok(Number(values(key)[0]) > 0);
const human = await (await fetchPublic(base)).text();
assert.equal(human.split('</head>')[0], head, 'Human and crawler metadata differ.');
const playerURL = new URL(values('twitter:player')[0]);
assert.equal(playerURL.origin, base.origin);
const player = await fetchPublic(playerURL);
assert.match(player.headers.get('content-type') || '', /text\/html/);
assert.equal(player.headers.get('x-frame-options'), null, 'Player has a conflicting framing header.');
const csp = player.headers.get('content-security-policy') || '';
assert.match(csp, /frame-ancestors/);
for (const origin of ['https://x.com', 'https://*.x.com', 'https://twitter.com', 'https://*.twitter.com']) assert.ok(csp.includes(origin), `CSP missing ${origin}`);
assert.ok(!csp.includes("frame-ancestors 'none'"));
assert.equal(response.headers.get('x-frame-options'), 'DENY');
const posterURL = new URL(values('twitter:image')[0]);
assert.equal(posterURL.protocol, 'https:');
const poster = await fetchPublic(posterURL, true);
assert.match(poster.headers.get('content-type') || '', /image\/png/);
const bytes = new Uint8Array(await poster.arrayBuffer());
assert.deepEqual([...bytes.slice(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10]);
assert.ok(bytes.length < 5_000_000);
console.log(JSON.stringify({ share: base.href, player: player.url, poster: poster.url, posterBytes: bytes.length, twitterSite: values('twitter:site')[0], framingPolicy: csp, result: 'Public HTTP checks passed; actual X rendering still requires an authorized post test.' }, null, 2));
